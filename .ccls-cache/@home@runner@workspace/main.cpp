#include <iostream>

int main() {
  double ml = 1.5;
  std::cout << "After five years the ocean's level will be higher by " << ml * 5
            << " ml." << std::endl;
  std::cout << "After seven years the ocean's level will be higher by "
            << ml * 7 << " ml." << std::endl;
  std::cout << "After ten years the ocean's level will be higher by " << ml * 10
            << " ml." << std::endl;
  return 0;
}